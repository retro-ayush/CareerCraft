drop table if exists support_tickets, returns, order_items, orders, products, customers cascade;

create table customers (
  id          text primary key,
  name        text not null,
  email       text not null,
  phone       text,
  city        text
);

create table products (
  id                  text primary key,
  name                text not null,
  category            text not null,
  price               numeric(10,2) not null,
  return_window_days  int not null default 7
);

create table orders (
  id                 int primary key,
  customer_id        text not null references customers(id),
  order_date         date not null,
  status             text not null check (status in ('placed','shipped','out_for_delivery','delivered','cancelled')),
  expected_delivery  date,
  delivered_date     date,
  total_amount       numeric(10,2) not null,
  courier            text,
  tracking_number    text
);

create table order_items (
  id          bigint generated always as identity primary key,
  order_id    int not null references orders(id) on delete cascade,
  product_id  text not null references products(id),
  quantity    int not null default 1,
  unit_price  numeric(10,2) not null
);

create table returns (
  id          bigint generated always as identity primary key,
  order_id    int not null references orders(id),
  product_id  text not null references products(id),
  reason      text not null,
  status      text not null default 'requested' check (status in ('requested','approved','picked_up','refunded','rejected')),
  created_at  timestamptz not null default now()
);

create table support_tickets (
  id           bigint generated always as identity primary key,
  customer_id  text not null references customers(id),
  order_id     int references orders(id),
  issue        text not null,
  priority     text not null default 'medium' check (priority in ('low','medium','high')),
  status       text not null default 'open' check (status in ('open','in_progress','resolved')),
  created_at   timestamptz not null default now()
);

